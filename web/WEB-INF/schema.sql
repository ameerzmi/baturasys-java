-- BaturaSys (Java) - Java DB / Apache Derby schema (tables only, no data).
-- Used automatically on first start when the database is empty (DbInit),
-- which then fills it with demo data. You can also run it by hand in NetBeans.

CREATE TABLE alerts (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  kind VARCHAR(40),
  severity VARCHAR(10) DEFAULT 'medium' CHECK (severity IN ('high','medium','low')),
  message VARCHAR(4000) NOT NULL,
  alert_date DATE,
  is_read SMALLINT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

CREATE TABLE bookings (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  ref VARCHAR(25) NOT NULL,
  customer_id INT,
  customer_name VARCHAR(100) NOT NULL,
  customer_phone VARCHAR(20),
  activity_id VARCHAR(10) NOT NULL,
  watercraft_id VARCHAR(10),
  booking_date DATE NOT NULL,
  slot VARCHAR(25) NOT NULL,
  hours INT DEFAULT 1,
  rental_type VARCHAR(10) DEFAULT 'On-site' CHECK (rental_type IN ('On-site','Off-site')),
  amount DECIMAL(10,2) NOT NULL,
  status VARCHAR(25) DEFAULT 'PENDING_PAYMENT' CHECK (status IN ('PENDING_PAYMENT','AWAITING_VERIFICATION','CONFIRMED','REJECTED','CHECKED_IN','COMPLETED','CANCELLED')),
  receipt_path VARCHAR(255),
  rejection_reason VARCHAR(4000),
  checkin_at TIMESTAMP,
  equipment_assigned VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP,
  checkout_at TIMESTAMP,
  return_notes VARCHAR(4000),
  group_ref VARCHAR(25),
  PRIMARY KEY (id),
  CONSTRAINT bookings_ref UNIQUE (ref)
);

CREATE INDEX idx_group_ref ON bookings (group_ref);

CREATE TABLE customers (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL,
  phone VARCHAR(20),
  ic_number VARCHAR(12),
  password_hash VARCHAR(255) NOT NULL,
  status VARCHAR(12) DEFAULT 'Active' NOT NULL CHECK (status IN ('Active','Deactivated')),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT customers_email UNIQUE (email)
);

CREATE TABLE equipment (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  equipment_id VARCHAR(10) NOT NULL,
  type VARCHAR(50) NOT NULL,
  size VARCHAR(20),
  condition_status VARCHAR(10) DEFAULT 'Good' CHECK (condition_status IN ('Good','Worn','Damaged','Missing')),
  purchase_date DATE,
  lifespan_months INT DEFAULT 24,
  replacement_due DATE,
  status VARCHAR(10) DEFAULT 'Active' CHECK (status IN ('Active','Flagged','Missing','Retired')),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT equipment_eqid UNIQUE (equipment_id)
);

CREATE TABLE login_attempts (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  identifier VARCHAR(150) NOT NULL,
  role VARCHAR(20) NOT NULL,
  fail_count INT DEFAULT 0 NOT NULL,
  locked_until TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT login_identifier_role UNIQUE (identifier, role)
);

CREATE TABLE maintenance_tasks (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  task_id VARCHAR(15) NOT NULL,
  watercraft_id VARCHAR(10) NOT NULL,
  type VARCHAR(50) NOT NULL,
  scheduled_date DATE,
  assignee_id VARCHAR(10),
  status VARCHAR(12) DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','IN_PROGRESS','COMPLETED','OVERDUE','APPROVED')),
  notes VARCHAR(4000),
  recurring_days INT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP,
  completed_at TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT maint_task_id UNIQUE (task_id)
);

CREATE TABLE managers (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  manager_id VARCHAR(10) NOT NULL,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100),
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT managers_mgr_id UNIQUE (manager_id)
);

CREATE TABLE settings (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  setting_key VARCHAR(50) NOT NULL,
  setting_value VARCHAR(4000),
  PRIMARY KEY (id),
  CONSTRAINT settings_key UNIQUE (setting_key)
);

CREATE TABLE staff (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  staff_id VARCHAR(10) NOT NULL,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100),
  phone VARCHAR(20),
  ic_number VARCHAR(12),
  role VARCHAR(20) DEFAULT 'Operations Staff' CHECK (role IN ('Operations Staff','Supervisor')),
  password_hash VARCHAR(255) NOT NULL,
  status VARCHAR(12) DEFAULT 'Active' CHECK (status IN ('Active','Deactivated')),
  last_login TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT staff_staff_id UNIQUE (staff_id),
  CONSTRAINT staff_ic UNIQUE (ic_number)
);

CREATE TABLE transactions (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  ref VARCHAR(100) NOT NULL,
  transaction_date DATE NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  method VARCHAR(30),
  type VARCHAR(10) NOT NULL CHECK (type IN ('Rental','Expense')),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

CREATE TABLE watercraft (
  id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  identifier VARCHAR(10) NOT NULL,
  name VARCHAR(50) NOT NULL,
  activity_id VARCHAR(10) NOT NULL CHECK (activity_id IN ('kayak','kayak2','canoe','paddle','cruise')),
  capacity INT DEFAULT 1 NOT NULL,
  rate_per_unit DECIMAL(8,2) DEFAULT 0.00 NOT NULL,
  year_acquired SMALLINT,
  status VARCHAR(20) DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','IN_USE','UNDER_MAINTENANCE','RETIRED')),
  usage_hours INT DEFAULT 0,
  last_maintenance DATE,
  next_maintenance DATE,
  condition_status VARCHAR(10) DEFAULT 'Good' CHECK (condition_status IN ('Good','Worn','Damaged')),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT watercraft_identifier UNIQUE (identifier),
  CONSTRAINT watercraft_name UNIQUE (name)
);
